#!/usr/bin/env python3
"""Regenerate bundled, locale-independent Unicode 17.0.0 width intervals.

Network access is a maintainer operation only; builds use the generated Telia file.
Use --check to verify that the checked-in tables match the pinned sources.
"""

import argparse
import hashlib
from pathlib import Path
import urllib.request

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "base/std/unicode/width_data.t"


def intervals(points):
    result = []
    for point in sorted(points):
        if result and result[-1][1] + 1 == point:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def generate():
    sources = {}
    for name in ("UnicodeData.txt", "EastAsianWidth.txt"):
        with urllib.request.urlopen(BASE + name, timeout=60) as response:
            sources[name] = response.read()
    categories = ["Cn"] * 0x110000
    first = 0
    for line in sources["UnicodeData.txt"].decode().splitlines():
        fields = line.split(";")
        point = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = point
        elif fields[1].endswith(", Last>"):
            categories[first:point + 1] = [fields[2]] * (point - first + 1)
        else:
            categories[point] = fields[2]
    wide = set()
    for line in sources["EastAsianWidth.txt"].decode().splitlines():
        value = line.split("#")[0].strip()
        if not value:
            continue
        span, prop = (part.strip() for part in value.split(";"))
        if prop not in ("W", "F"):
            continue
        bounds = span.split("..")
        wide.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    zero = {p for p, c in enumerate(categories) if c in ("Mn", "Mc", "Me", "Cf")}
    for start, end in ((0x1160, 0x11FF), (0xD7B0, 0xD7C6), (0xD7CB, 0xD7FB), (0x1F3FB, 0x1F3FF)):
        zero.update(range(start, end + 1))
    bad = {p for p, c in enumerate(categories) if c in ("Cc", "Cn", "Zl", "Zp")}
    lines = ["// Generated by scripts/generate-unicode-width.py; do not edit.",
             f"// Unicode {VERSION}; Unicode License V3: data/LICENSE-UNICODE.txt."]
    for name, data in sources.items():
        lines += [f"// {BASE}{name}", f"// SHA256 {hashlib.sha256(data).hexdigest()}"]
    lines += ["package unicode", ""]
    for name, points in (("nonprintable", bad), ("zero_width", zero), ("wide", wide)):
        ranges = intervals(points)
        lines += [f"fn {name}(point u32) bool {{", f"    ranges u32[{len(ranges) * 2}] := .{{"]
        lines += [f"        {start}, {end}," for start, end in ranges]
        lines += ["    }", "    return in_ranges(point, ranges[:])", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate()
    if args.check:
        if TARGET.read_text() != data:
            raise SystemExit("Unicode width tables differ; regenerate and review the diff")
    else:
        TARGET.write_text(data)


if __name__ == "__main__":
    main()
